/**
 * Copies clients/playkit/playkit.json and prompts/*.txt into src/playkit/kit-data.ts (the TypeScript twin of the Go
 * core's `go generate ./internal/playkit`): the app bundles the kit without reaching outside this project.
 * test/playkit-vectors.test.ts fails when the copy is stale. Run: npm run sync-playkit
 */
import { readFileSync, readdirSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const src = join(here, '..', '..', 'playkit');
const lf = (s: string) => s.replace(/\r\n/g, '\n');
const config = lf(readFileSync(join(src, 'playkit.json'), 'utf8'));
const templates: Record<string, string> = {};
for (const f of readdirSync(join(src, 'prompts')).filter((f) => f.endsWith('.txt')).sort()) {
  templates[f.slice(0, -4)] = lf(readFileSync(join(src, 'prompts', f), 'utf8'));
}
const out = `/* Generated by scripts/sync-playkit.ts from clients/playkit (MIT). Do not edit: run \`npm run sync-playkit\`. */
export const PLAYKIT_JSON = ${JSON.stringify(config)};

export const TEMPLATES: Record<string, string> = ${JSON.stringify(templates, null, 2)};
`;
writeFileSync(join(here, '..', 'src', 'playkit', 'kit-data.ts'), out);
console.log(`kit-data.ts: playkit.json and ${Object.keys(templates).length} templates`);
