function isPt(lang: string): boolean {
  return lang.toLowerCase().startsWith('pt');
}

export function mt(lang: string, key: string, params: Record<string, string | number> = {}): string {
  const table = isPt(lang) ? pt : en;
  const raw = table[key] ?? en[key] ?? key;
  return raw.replace(/\{(\w+)\}/g, (_, k: string) => (k in params ? String(params[k]) : `{${k}}`));
}

export function mlist(lang: string, key: string): string[] {
  return (isPt(lang) ? ptLists : enLists)[key] ?? enLists[key] ?? [];
}
